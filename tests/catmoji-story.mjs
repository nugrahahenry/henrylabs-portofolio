import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium, expect } from "@playwright/test";

const base = process.env.PORTFOLIO_URL ?? "http://localhost:3002";
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH ?? "C:/Program Files/Google/Chrome/Application/chrome.exe" });
mkdirSync("test-results/catmoji-story", { recursive: true });
try {
  for (const [width, height, lang] of process.argv.includes("--recovery") ? [] : [[1440, 900, "en"], [768, 1024, "en"], [390, 844, "id"], [320, 740, "en"], [844, 390, "id"]]) {
    const page = await browser.newPage({ viewport: { width, height }, hasTouch: width < 500, reducedMotion: width === 320 ? "reduce" : "no-preference" });
    const errors = [], outgoing = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("request", request => { if (/catmoji\.vercel|mediapipe|api\/tts|owner\.js/.test(request.url())) outgoing.push(request.url()); });
    await page.goto(`${base}/projects/catmoji?from=universe&lang=${lang}`);
    await expect(page.locator("html")).toHaveAttribute("data-preferences-ready", "true");
    await expect(page.locator("h1")).toHaveText("Catmoji");
    const panel = page.getByRole("tabpanel"), normal = page.getByRole("tab", { name: "Normal", exact: true }), challenge = page.getByRole("tab", { name: "Challenge", exact: true });
    const opener = panel.locator(".project-visual-open");
    await expect(normal).toHaveAttribute("aria-selected", "true");
    await expect(panel.locator("img")).toHaveJSProperty("complete", true);
    const first = await opener.boundingBox();
    const reserved = await panel.boundingBox();
    if (height > 600) assert.ok(first.y < height - 75, `first viewport contains product evidence: ${first.y}`);
    await page.screenshot({ path: `test-results/catmoji-story/${width}-opening.png` });
    await normal.focus();
    await page.keyboard.press("ArrowRight");
    await expect(challenge).toBeFocused();
    await expect(challenge).toHaveAttribute("aria-selected", "true");
    await expect(panel.locator("img")).toHaveAttribute("src", /challenge-panel/);
    assert.ok(Math.abs((await panel.boundingBox()).height - reserved.height) < 1, "mode change cannot resize the gallery");
    await page.keyboard.press("Home");
    await expect(normal).toHaveAttribute("aria-selected", "true");
    if (width < 500) await challenge.tap(); else await challenge.click();
    await page.locator(".catmoji-gallery").scrollIntoViewIfNeeded();
    await page.screenshot({ path: `test-results/catmoji-story/${width}-gallery.png` });
    await opener.click();
    const dialog = page.getByRole("dialog");
    await expect(dialog).toContainText(lang === "en" ? "Camera off" : "Kamera nonaktif");
    await expect(dialog).not.toContainText("Fictional sample photos");
    const zoom = dialog.getByRole("button", { name: lang === "en" ? "Zoom screenshot" : "Perbesar screenshot", exact: true });
    await expect(zoom).toBeEnabled();
    await zoom.click();
    await expect(dialog.locator(".project-art-stage")).toBeFocused();
    await page.keyboard.press("ArrowRight");
    await expect.poll(() => dialog.locator(".project-art-stage").evaluate(n => n.scrollLeft)).toBeGreaterThan(0);
    await page.keyboard.press("Escape");
    await expect(opener).toBeFocused();
    await page.locator(".catmoji-result").scrollIntoViewIfNeeded();
    const mobile = page.locator(".catmoji-mobile-proof .project-visual-open");
    await mobile.click();
    await expect(page.getByRole("dialog")).toContainText(lang === "en" ? "Camera off" : "Kamera nonaktif");
    await page.keyboard.press("Escape");
    await expect(mobile).toBeFocused();
    await page.screenshot({ path: `test-results/catmoji-story/${width}-result.png` });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "no horizontal overflow");
    for (const text of await page.locator(".catmoji-story h2, .catmoji-story h3, .catmoji-story p").all()) assert.ok(await text.evaluate(n => n.scrollWidth <= n.clientWidth + 1), "copy fits");
    await expect(page.locator(".detail-route a")).toHaveAttribute("href", /world=catmoji/);
    await expect(page.locator(".detail-actions a").first()).toHaveAttribute("href", "https://catmoji.vercel.app/");
    await expect(page.locator(".detail-contact")).toBeVisible();
    assert.deepEqual(outgoing, [], "reading never loads Catmoji, camera model or voice providers");
    assert.deepEqual(errors, []);
    await page.evaluate(async () => { document.activeElement?.blur(); window.scrollTo({ top: 0, behavior: "instant" }); await document.fonts.ready; });
    await page.waitForTimeout(600);
    await page.screenshot({ path: `test-results/catmoji-story/${width}-page.png`, fullPage: true });
    await page.close();
    console.log(`PASS Catmoji ${width}x${height} ${lang}: stable tabs, keyboard/touch, screenshot viewer, focus, layout and privacy`);
  }
  const page = await browser.newPage();
  await page.goto(`${base}/projects?q=catmoji&lang=id&motion=off`);
  await page.locator("#project-card-catmoji").click();
  await expect(page.locator(".catmoji-story")).toBeVisible();
  await page.locator(".detail-route a").click();
  await expect(page.locator("#project-card-catmoji")).toBeFocused();
  await expect(page.locator(".project-record")).toHaveCount(1);
  let fail = true;
  await page.route("**/assets/projects/catmoji/normal-panel.webp*", route => fail ? route.abort() : route.continue());
  await page.goto(`${base}/projects/catmoji?lang=en&motion=off&chapter=tools&tool=javascript&group=build`);
  await expect(page.locator(".detail-route a")).toHaveAttribute("href", /chapter=tools.*tool=javascript/);
  const retry = page.getByRole("button", { name: "Retry screenshot", exact: true });
  await page.locator(".catmoji-gallery").scrollIntoViewIfNeeded();
  await expect(retry).toBeVisible();
  await expect(page.getByRole("tabpanel").locator(".project-visual-open")).toBeDisabled();
  fail = false;
  await retry.click();
  await expect(page.getByRole("tabpanel").locator(".project-visual-open")).toBeEnabled();
  await page.getByRole("tabpanel").locator(".project-visual-open").click();
  await expect(page.getByRole("button", { name: "Zoom screenshot", exact: true })).toBeEnabled();
  await page.keyboard.press("Escape");
  console.log("PASS Catmoji filtered return, maker return, failed image and recovery");
  await page.close();
} finally { await browser.close(); }
